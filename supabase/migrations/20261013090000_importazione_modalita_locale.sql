-- Importazione dei dati della Modalità locale nell'account (ADR-0005,
-- ADR-0007, #173). Il device legge drift, carica prima le immagini su
-- Storage e poi chiama `importa_modalita_locale` con un payload jsonb che
-- porta gli id drift: la funzione li rimappa sugli id Postgres e scrive
-- tutto in un'unica transazione nella Collezione di cui l'utente è `owner`.
--
-- Idempotenza: `import_id` è scelto dal device quando l'utente accetta e
-- riusato a ogni nuovo tentativo. La riga in `importazioni` nasce nella
-- stessa transazione dei dati: se c'è, l'importazione è già avvenuta e la
-- funzione restituisce l'esito salvato senza scrivere nulla; se la
-- transazione fallisce a metà non resta niente, e il tentativo successivo
-- riparte da zero.

create table public.importazioni (
  id uuid primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  collection_id uuid not null references public.collections (id) on delete cascade,
  esito jsonb,
  created_at timestamptz not null default now()
);

create index importazioni_user_id_idx on public.importazioni (user_id);
create index importazioni_collection_id_idx on public.importazioni (collection_id);

alter table public.importazioni enable row level security;

create policy "creator reads own imports" on public.importazioni
for select to authenticated
using ( user_id = (select auth.uid()) );

create policy "creator writes own imports" on public.importazioni
for all to authenticated
using ( user_id = (select auth.uid()) )
with check ( user_id = (select auth.uid()) );

-- Una mappa jsonb { "<id drift>": <id Postgres> } con un id nuovo dalla
-- sequence della tabella per ogni riga del payload: gli insert passano
-- l'id esplicito (le colonne sono `generated by default`), così le FK si
-- rimappano senza leggere nulla indietro.
create function private.mappa_id(righe jsonb, tabella text)
returns jsonb
language sql
volatile
set search_path = ''
as $$
  select coalesce(
    jsonb_object_agg(riga->>'id', nextval(pg_get_serial_sequence(tabella, 'id'))),
    '{}'::jsonb
  )
  from jsonb_array_elements(coalesce(righe, '[]'::jsonb)) as riga
$$;

revoke execute on function private.mappa_id(jsonb, text) from public;
grant execute on function private.mappa_id(jsonb, text) to authenticated;

-- Il payload ha una chiave per tabella (nomi delle tabelle Postgres), ogni
-- riga con i nomi di colonna Postgres e gli id drift in `id` e nelle FK.
-- Le immagini (`edizioni.cover_image`, `serie.cover_image`,
-- `scansioni.image`) arrivano già come chiavi Storage o URL remoti. Una FK
-- verso una riga assente dal payload diventa null (es. la Scansione già
-- risolta di una Copia, che non migra).
create function public.importa_modalita_locale(payload jsonb, import_id uuid)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_collection_id uuid;
  v_esito jsonb;
  m_opere jsonb;
  m_serie jsonb;
  m_edizioni jsonb;
  m_copie jsonb;
  m_creator jsonb;
  m_tag jsonb;
  m_character jsonb;
  m_scansioni jsonb;
  m_identificazione jsonb;
begin
  if v_user_id is null then
    raise exception 'importa_modalita_locale richiede un utente autenticato'
      using errcode = '42501';
  end if;

  select collection_id into v_collection_id
  from public.collection_members
  where user_id = v_user_id and role = 'owner';
  if v_collection_id is null then
    raise exception 'nessuna Collezione di proprietà per l''utente'
      using errcode = 'P0002';
  end if;

  -- Prima della scrittura dei dati: un secondo tentativo concorrente con lo
  -- stesso id resta in attesa qui finché il primo non finisce.
  insert into public.importazioni (id, user_id, collection_id)
  values (import_id, v_user_id, v_collection_id)
  on conflict (id) do nothing;
  if not found then
    select esito into v_esito from public.importazioni where id = import_id;
    if v_esito is null then
      raise exception 'importazione % non appartiene all''utente', import_id
        using errcode = '42501';
    end if;
    return v_esito;
  end if;

  -- Catalogo ----------------------------------------------------------------

  m_opere := private.mappa_id(payload->'opere', 'public.opere');
  insert into public.opere (id, collection_id, created_by, title, created_at)
  select (m_opere->>(riga->>'id'))::bigint, v_collection_id, v_user_id,
         r.title, coalesce(r.created_at, now())
  from jsonb_array_elements(coalesce(payload->'opere', '[]')) as riga,
       jsonb_populate_record(null::public.opere, riga) as r;

  m_serie := private.mappa_id(payload->'serie', 'public.serie');
  insert into public.serie (id, collection_id, created_by, name, total_issues,
                            issn, cover_image)
  select (m_serie->>(riga->>'id'))::bigint, v_collection_id, v_user_id,
         r.name, r.total_issues, r.issn, r.cover_image
  from jsonb_array_elements(coalesce(payload->'serie', '[]')) as riga,
       jsonb_populate_record(null::public.serie, riga) as r;

  m_edizioni := private.mappa_id(payload->'edizioni', 'public.edizioni');
  insert into public.edizioni (id, collection_id, created_by, opera_id, serie_id,
                               publisher, issue_number, issue_number_label,
                               cover_image, release_date, cover_price, page_count,
                               language, color, ean, created_at, volume,
                               description, printing_type, classificazione,
                               year, format)
  select (m_edizioni->>(riga->>'id'))::bigint, v_collection_id, v_user_id,
         (m_opere->>(riga->>'opera_id'))::bigint,
         (m_serie->>(riga->>'serie_id'))::bigint,
         r.publisher, r.issue_number, r.issue_number_label, r.cover_image,
         r.release_date, r.cover_price, r.page_count, r.language, r.color,
         r.ean, coalesce(r.created_at, now()), r.volume, r.description, r.printing_type,
         r.classificazione, r.year, r.format
  from jsonb_array_elements(coalesce(payload->'edizioni', '[]')) as riga,
       jsonb_populate_record(null::public.edizioni, riga) as r;

  m_creator := private.mappa_id(payload->'creator', 'public.creator');
  insert into public.creator (id, collection_id, created_by, name)
  select (m_creator->>(riga->>'id'))::bigint, v_collection_id, v_user_id, r.name
  from jsonb_array_elements(coalesce(payload->'creator', '[]')) as riga,
       jsonb_populate_record(null::public.creator, riga) as r;

  insert into public.comic_creator (collection_id, created_by, edizione_id,
                                    creator_id, ruolo)
  select v_collection_id, v_user_id,
         (m_edizioni->>(riga->>'edizione_id'))::bigint,
         (m_creator->>(riga->>'creator_id'))::bigint, r.ruolo
  from jsonb_array_elements(coalesce(payload->'comic_creator', '[]')) as riga,
       jsonb_populate_record(null::public.comic_creator, riga) as r;

  m_tag := private.mappa_id(payload->'tag', 'public.tag');
  insert into public.tag (id, collection_id, created_by, name)
  select (m_tag->>(riga->>'id'))::bigint, v_collection_id, v_user_id, r.name
  from jsonb_array_elements(coalesce(payload->'tag', '[]')) as riga,
       jsonb_populate_record(null::public.tag, riga) as r;

  insert into public.edizione_tag (collection_id, created_by, edizione_id, tag_id)
  select v_collection_id, v_user_id,
         (m_edizioni->>(riga->>'edizione_id'))::bigint,
         (m_tag->>(riga->>'tag_id'))::bigint
  from jsonb_array_elements(coalesce(payload->'edizione_tag', '[]')) as riga;

  m_character := private.mappa_id(payload->'character', 'public.character');
  insert into public.character (id, collection_id, created_by, name)
  select (m_character->>(riga->>'id'))::bigint, v_collection_id, v_user_id, r.name
  from jsonb_array_elements(coalesce(payload->'character', '[]')) as riga,
       jsonb_populate_record(null::public.character, riga) as r;

  insert into public.comic_character (collection_id, created_by, edizione_id,
                                      character_id)
  select v_collection_id, v_user_id,
         (m_edizioni->>(riga->>'edizione_id'))::bigint,
         (m_character->>(riga->>'character_id'))::bigint
  from jsonb_array_elements(coalesce(payload->'comic_character', '[]')) as riga;

  insert into public.edizione_genere (collection_id, created_by, edizione_id, genere)
  select v_collection_id, v_user_id,
         (m_edizioni->>(riga->>'edizione_id'))::bigint, r.genere
  from jsonb_array_elements(coalesce(payload->'edizione_genere', '[]')) as riga,
       jsonb_populate_record(null::public.edizione_genere, riga) as r;

  -- Scansioni non ancora risolte in una Copia (private all'utente) ----------

  m_scansioni := private.mappa_id(payload->'scansioni', 'public.scansioni');
  insert into public.scansioni (id, user_id, collection_id, image, created_at)
  select (m_scansioni->>(riga->>'id'))::bigint, v_user_id, v_collection_id,
         r.image, coalesce(r.created_at, now())
  from jsonb_array_elements(coalesce(payload->'scansioni', '[]')) as riga,
       jsonb_populate_record(null::public.scansioni, riga) as r;

  insert into public.analisi_copertina (user_id, scansione_id, title,
                                        issue_number_label, publisher,
                                        series_name, isbn, barcode, price,
                                        release_date, year, page_count,
                                        language, color, issn, characters,
                                        cover_style_tags, visual_element_tags,
                                        recognized_publisher_logo,
                                        recognized_series_logo, printing_type,
                                        classificazione, description,
                                        raw_response, status, error_message,
                                        completed_at, created_at)
  select v_user_id, (m_scansioni->>(riga->>'scansione_id'))::bigint,
         r.title, r.issue_number_label, r.publisher, r.series_name, r.isbn,
         r.barcode, r.price, r.release_date, r.year, r.page_count, r.language,
         r.color, r.issn, coalesce(r.characters, '{}'),
         coalesce(r.cover_style_tags, '{}'), coalesce(r.visual_element_tags, '{}'),
         r.recognized_publisher_logo, r.recognized_series_logo,
         r.printing_type, r.classificazione, r.description, r.raw_response,
         coalesce(r.status, 'pending'), r.error_message, r.completed_at,
         coalesce(r.created_at, now())
  from jsonb_array_elements(coalesce(payload->'analisi_copertina', '[]')) as riga,
       jsonb_populate_record(null::public.analisi_copertina, riga) as r;

  m_identificazione := private.mappa_id(payload->'identificazione', 'public.identificazione');
  insert into public.identificazione (id, user_id, scansione_id, status,
                                      error_message, created_at, completed_at)
  select (m_identificazione->>(riga->>'id'))::bigint, v_user_id,
         (m_scansioni->>(riga->>'scansione_id'))::bigint,
         coalesce(r.status, 'pending'), r.error_message,
         coalesce(r.created_at, now()), r.completed_at
  from jsonb_array_elements(coalesce(payload->'identificazione', '[]')) as riga,
       jsonb_populate_record(null::public.identificazione, riga) as r;

  insert into public.candidati (user_id, identificazione_id, source, edizione_id,
                                title, series_name, issue_number_label,
                                publisher, year, cover_image_url, punteggio,
                                scelto)
  select v_user_id, (m_identificazione->>(riga->>'identificazione_id'))::bigint,
         r.source, (m_edizioni->>(riga->>'edizione_id'))::bigint, r.title,
         r.series_name, r.issue_number_label, r.publisher, r.year,
         r.cover_image_url, r.punteggio, coalesce(r.scelto, false)
  from jsonb_array_elements(coalesce(payload->'candidati', '[]')) as riga,
       jsonb_populate_record(null::public.candidati, riga) as r;

  -- Copie (dopo le Scansioni, che possono riferire) --------------------------

  m_copie := private.mappa_id(payload->'copie', 'public.copie');
  insert into public.copie (id, collection_id, created_by, edizione_id, status,
                            reading_status, condition, purchase_price,
                            purchase_price_currency, purchase_date, seller,
                            valutazione, location, notes, created_at,
                            updated_at, scansione_id, for_sale)
  select (m_copie->>(riga->>'id'))::bigint, v_collection_id, v_user_id,
         (m_edizioni->>(riga->>'edizione_id'))::bigint, r.status,
         r.reading_status, r.condition, r.purchase_price,
         r.purchase_price_currency, r.purchase_date, r.seller, r.valutazione,
         r.location, r.notes, coalesce(r.created_at, now()),
         coalesce(r.updated_at, r.created_at, now()),
         (m_scansioni->>(riga->>'scansione_id'))::bigint,
         coalesce(r.for_sale, false)
  from jsonb_array_elements(coalesce(payload->'copie', '[]')) as riga,
       jsonb_populate_record(null::public.copie, riga) as r;

  insert into public.valore_stimato (collection_id, created_by, copia_id, status,
                                     value, error_message, completed_at,
                                     created_at)
  select v_collection_id, v_user_id, (m_copie->>(riga->>'copia_id'))::bigint,
         r.status, r.value, r.error_message, r.completed_at,
         coalesce(r.created_at, now())
  from jsonb_array_elements(coalesce(payload->'valore_stimato', '[]')) as riga,
       jsonb_populate_record(null::public.valore_stimato, riga) as r;

  v_esito := jsonb_build_object(
    'copie_importate', jsonb_array_length(coalesce(payload->'copie', '[]')),
    'scansioni_importate', jsonb_array_length(coalesce(payload->'scansioni', '[]')),
    'copie_collezione', (select count(*) from public.copie
                         where collection_id = v_collection_id)
  );
  update public.importazioni set esito = v_esito where id = import_id;
  return v_esito;
end;
$$;

revoke execute on function public.importa_modalita_locale(jsonb, uuid) from public, anon;
grant execute on function public.importa_modalita_locale(jsonb, uuid) to authenticated;
